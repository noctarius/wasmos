C_HELPERS = r"""static inline void wasmos_error_init(wasmos_error_t *e) {
    e->transport = WASMOS_OK;
    e->flags = 0;
    for (int i = 0; i < WASMOS_ERR_CHAIN_DEPTH; ++i) {
        e->chain[i].domain = 0;
        e->chain[i].code = 0;
        e->chain[i].origin = 0;
    }
}

static inline bool wasmos_error_ok(const wasmos_error_t *e) {
    return e->transport == WASMOS_OK && e->chain[0].domain == 0;
}

static inline wasmos_error_code_t wasmos_error_head(const wasmos_error_t *e) {
    return WASMOS_ERR_MAKE(e->chain[0].domain, e->chain[0].code);
}

static inline wasmos_error_code_t wasmos_error_root(const wasmos_error_t *e) {
    int i = 0;
    while (i + 1 < WASMOS_ERR_CHAIN_DEPTH && e->chain[i + 1].domain != 0) {
        ++i;
    }
    return WASMOS_ERR_MAKE(e->chain[i].domain, e->chain[i].code);
}

static inline wasmos_error_code_t wasmos_error_unwrap(const wasmos_error_t *e) {
    if (WASMOS_ERR_CHAIN_DEPTH < 2 || e->chain[1].domain == 0) {
        return WASMOS_ERR_NONE;
    }
    return WASMOS_ERR_MAKE(e->chain[1].domain, e->chain[1].code);
}

static inline bool wasmos_error_is(const wasmos_error_t *e, wasmos_error_code_t sentinel) {
    for (int i = 0; i < WASMOS_ERR_CHAIN_DEPTH; ++i) {
        if (e->chain[i].domain == 0) {
            break;
        }
        if (WASMOS_ERR_MAKE(e->chain[i].domain, e->chain[i].code) == sentinel) {
            return true;
        }
    }
    return false;
}

static inline bool wasmos_error_as(const wasmos_error_t *e, wasmos_error_domain_t dom,
                                   uint16_t *out_code) {
    for (int i = 0; i < WASMOS_ERR_CHAIN_DEPTH; ++i) {
        if (e->chain[i].domain == 0) {
            break;
        }
        if (e->chain[i].domain == dom) {
            if (out_code) {
                *out_code = e->chain[i].code;
            }
            return true;
        }
    }
    return false;
}

static inline void wasmos_error_set(wasmos_error_t *e, wasmos_error_domain_t dom,
                                    uint16_t code, uint32_t origin) {
    wasmos_error_init(e);
    e->chain[0].domain = dom;
    e->chain[0].code = code;
    e->chain[0].origin = origin;
}

static inline void wasmos_error_wrap(wasmos_error_t *e, wasmos_error_domain_t dom,
                                     uint16_t code, uint32_t origin) {
    int last = WASMOS_ERR_CHAIN_DEPTH - 1;
    if (e->chain[last].domain != 0) {
        for (int i = last - 1; i >= 1; --i) {
            e->chain[i] = e->chain[i - 1];
        }
        e->flags |= WASMOS_ERR_FLAG_TRUNCATED;
    } else {
        for (int i = last; i >= 1; --i) {
            e->chain[i] = e->chain[i - 1];
        }
    }
    e->chain[0].domain = dom;
    e->chain[0].code = code;
    e->chain[0].origin = origin;
}

static inline size_t wasmos_strerror_chain(const wasmos_error_t *e, char *buf, size_t n) {
    size_t w = 0;
    if (n == 0) {
        return 0;
    }
    for (int i = 0; i < WASMOS_ERR_CHAIN_DEPTH; ++i) {
        if (e->chain[i].domain == 0) {
            break;
        }
        if (i > 0) {
            const char *sep = " <- ";
            while (*sep && w + 1 < n) {
                buf[w++] = *sep++;
            }
        }
        wasmos_error_code_t packed = WASMOS_ERR_MAKE(e->chain[i].domain, e->chain[i].code);
        const char *dom = wasmos_error_domain_name(e->chain[i].domain);
        while (*dom && w + 1 < n) {
            buf[w++] = *dom++;
        }
        const char *colon = ": ";
        while (*colon && w + 1 < n) {
            buf[w++] = *colon++;
        }
        const char *desc = wasmos_strerror(packed);
        while (*desc && w + 1 < n) {
            buf[w++] = *desc++;
        }
    }
    if (w == 0) {
        const char *ok = "success";
        while (*ok && w + 1 < n) {
            buf[w++] = *ok++;
        }
    }
    buf[w] = '\0';
    return w;
}
"""


RUST_HELPERS = r"""
// Fixed error object (value ABI) + chain helpers (pure value ops). IPC framing
// lives in the libsys wrappers.
pub const WASMOS_ERR_CHAIN_DEPTH: usize = 4;
pub const WASMOS_ERR_FLAG_TRUNCATED: u32 = 1;

#[repr(C)]
#[derive(Copy, Clone)]
pub struct WasmosFrame {
    pub domain: u16,
    pub code: u16,
    pub origin: u32,
}

#[repr(C)]
#[derive(Copy, Clone)]
pub struct WasmosError {
    pub transport: i32,
    pub flags: u32,
    pub chain: [WasmosFrame; WASMOS_ERR_CHAIN_DEPTH],
}

impl WasmosError {
    pub const fn new() -> Self {
        WasmosError {
            transport: WASMOS_OK,
            flags: 0,
            chain: [WasmosFrame { domain: 0, code: 0, origin: 0 }; WASMOS_ERR_CHAIN_DEPTH],
        }
    }
    pub fn is_ok(&self) -> bool {
        self.transport == WASMOS_OK && self.chain[0].domain == 0
    }
    pub fn head(&self) -> u32 {
        wasmos_err_make(self.chain[0].domain, self.chain[0].code)
    }
    pub fn root(&self) -> u32 {
        let mut i = 0;
        while i + 1 < WASMOS_ERR_CHAIN_DEPTH && self.chain[i + 1].domain != 0 {
            i += 1;
        }
        wasmos_err_make(self.chain[i].domain, self.chain[i].code)
    }
    pub fn unwrap_cause(&self) -> u32 {
        if WASMOS_ERR_CHAIN_DEPTH < 2 || self.chain[1].domain == 0 {
            return WASMOS_ERR_NONE;
        }
        wasmos_err_make(self.chain[1].domain, self.chain[1].code)
    }
    pub fn is(&self, sentinel: u32) -> bool {
        for f in &self.chain {
            if f.domain == 0 {
                break;
            }
            if wasmos_err_make(f.domain, f.code) == sentinel {
                return true;
            }
        }
        false
    }
    pub fn as_domain(&self, dom: u16) -> Option<u16> {
        for f in &self.chain {
            if f.domain == 0 {
                break;
            }
            if f.domain == dom {
                return Some(f.code);
            }
        }
        None
    }
    pub fn set(&mut self, dom: u16, code: u16, origin: u32) {
        *self = WasmosError::new();
        self.chain[0] = WasmosFrame { domain: dom, code, origin };
    }
    pub fn wrap(&mut self, dom: u16, code: u16, origin: u32) {
        let last = WASMOS_ERR_CHAIN_DEPTH - 1;
        let start = if self.chain[last].domain != 0 {
            self.flags |= WASMOS_ERR_FLAG_TRUNCATED;
            last - 1
        } else {
            last
        };
        let mut i = start;
        while i >= 1 {
            self.chain[i] = self.chain[i - 1];
            i -= 1;
        }
        self.chain[0] = WasmosFrame { domain: dom, code, origin };
    }
}
"""


