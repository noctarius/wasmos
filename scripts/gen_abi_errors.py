def emit_docs(m):
    """Markdown error/status reference: the transport axis + every domain's codes."""
    o = [
        "<!-- GENERATED by scripts/gen_abi_errors.py from abi/errors.yaml — DO NOT EDIT. -->",
        "# WASMOS Error / Status Codes",
        "",
        "Two axes: **transport** (`wasmos_status_t`, the global call-mechanism result)",
        "and **domains** (namespaced operation errors, packed as `(domain << 16) | code`).",
        "",
        "## Transport (`wasmos_status_t`)",
        "",
        "| Name | Value | Description |",
        "|---|---|---|",
    ]
    for t in m.transport:
        desc = str(t.get("description", "")).replace("|", "\\|")
        o.append(f"| `WASMOS_{t['name']}` | {int(t['value'])} | {desc} |")
    o.append("")
    o.append("## Domains")
    o.append("")
    for dname, d in m.domains.items():
        did = int(d["id"])
        ddesc = str(d.get("description", "")).replace("|", "\\|")
        o.append(f"### `{dname}` (domain {did}) — {ddesc}")
        o.append("")
        codes = [p for p in m.packed if p["domain_id"] == did]
        if not codes:
            o.append("*(no codes)*")
            o.append("")
            continue
        o.append("| Code | Packed | Description |")
        o.append("|---|---|---|")
        for p in codes:
            desc = str(p["desc"]).replace("|", "\\|")
            o.append(f"| `{p['const']}` | 0x{p['packed']:08X} | {desc} |")
        o.append("")
    return "\n".join(o)


EMITTERS = {
    "c": ("c/wasmos_status.h", emit_c),
    "rust": ("rust/wasmos_status.rs", emit_rust),
    "go": ("go/wasmos_status.go", emit_go),
    "zig": ("zig/wasmos_status.zig", emit_zig),
    "assemblyscript": ("assemblyscript/wasmos_status.ts", emit_as),
}

# Always emitted on a full run (not a per-language --lang choice).
EXTRA_OUTPUTS = [("docs/errors.md", emit_docs)]


def main():
    ap = argparse.ArgumentParser(description="Generate the wasmos error/status ABI.")
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if any on-disk file differs from the IDL",
    )
    ap.add_argument("--lang", choices=sorted(EMITTERS), help="restrict to one language")
    args = ap.parse_args()

    try:
        model = Model(load_idl())
    except YamlUnavailable as exc:
        if args.check:
            print(f"gen_abi_errors: skipping check ({exc})", file=sys.stderr)
            return
        die(str(exc))

    langs = [args.lang] if args.lang else list(EMITTERS)
    outputs = [EMITTERS[lang] for lang in langs]
    if not args.lang:
        outputs += EXTRA_OUTPUTS  # docs/errors.md on a full run
    stale = False
    for rel, emit in outputs:
        text = emit(model)
        path = os.path.join(GEN_ROOT, rel)
        if args.check:
            try:
                with open(path, "r", encoding="utf-8") as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != text:
                print(
                    f"gen_abi_errors: {os.path.relpath(path, REPO_ROOT)} is stale",
                    file=sys.stderr,
                )
                stale = True
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"gen_abi_errors: wrote {os.path.relpath(path, REPO_ROOT)}")

    if args.check:
        if stale:
            print(
                "gen_abi_errors: run scripts/gen_abi_errors.py to regenerate",
                file=sys.stderr,
            )
            sys.exit(2)
        print("gen_abi_errors: all generated ABI files are up to date")


if __name__ == "__main__":
    main()
