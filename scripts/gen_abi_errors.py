def emit_go(m):
    o = []
    w = o.append
    w(f"// {BANNER}")
    w(f"// {BANNER2}")
    w("// Value ABI only (constants + accessors + decode). The fixed error object")
    w("// and chain helpers live with the libsys wrappers.")
    w("")
    w("package wasmosstatus")
    w("")
    w(f"const WasmosABIErrorsVersion uint32 = {m.version}")
    w("")
    w("// Transport / kernel-IPC result axis.")
    w("const (")
    for t in m.transport:
        w(
            f"\tWASMOS_{t['name']} int32 = {int(t['value'])} // {t.get('description','')}"
        )
    w(")")
    w("")
    w("// Domain registry (stable ids).")
    w("const (")
    for name, d in m.domains.items():
        w(f"\tWASMOS_ERR_DOMAIN_{name.upper()} uint16 = {int(d['id'])}")
    w(")")
    w("")
    w("const WASMOS_ERR_NONE uint32 = 0")
    w("")
    w("// Packed domain error constants: (domain << 16) | local_code.")
    w("const (")
    for p in m.packed:
        w(f"\t{p['const']} uint32 = 0x{p['packed']:08X} // {p['desc']}")
    w(")")
    w("")
    w("func WasmosErrMake(dom uint16, code uint16) uint32 {")
    w("\treturn (uint32(dom) << 16) | uint32(code)")
    w("}")
    w("func WasmosErrDomainOf(x uint32) uint16 { return uint16(x >> 16) }")
    w("func WasmosErrCodeOf(x uint32) uint16   { return uint16(x & 0xffff) }")
    w("")
    w("func WasmosStatusStr(s int32) string {")
    w("\tswitch s {")
    for t in m.transport:
        w(f"\tcase WASMOS_{t['name']}:")
        w(f'\t\treturn "{t["name"]}"')
    w("\tdefault:")
    w('\t\treturn "UNKNOWN_STATUS"')
    w("\t}")
    w("}")
    w("")
    w("func WasmosErrorDomainName(d uint16) string {")
    w("\tswitch d {")
    for name, d in m.domains.items():
        w(f"\tcase WASMOS_ERR_DOMAIN_{name.upper()}:")
        w(f'\t\treturn "{name}"')
    w("\tdefault:")
    w('\t\treturn "unknown"')
    w("\t}")
    w("}")
    w("")
    w("func WasmosStrerror(c uint32) string {")
    w("\tswitch c {")
    w("\tcase WASMOS_ERR_NONE:")
    w('\t\treturn "success"')
    for p in m.packed:
        w(f"\tcase {p['const']}:")
        w(f'\t\treturn "{esc(p["desc"])}"')
    w("\tdefault:")
    w('\t\treturn "unknown error"')
    w("\t}")
    w("}")
    w("")
    return "\n".join(o)


