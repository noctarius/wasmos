//! fixtures_disk_images.zig — on-disk bytes captured from real writers.
//!
//! Every array here was produced once by a tool that actually writes the format
//! and pasted in verbatim. Nothing is constructed. That is the point: a suite
//! built entirely from images it writes itself cannot detect the one failure
//! mode that matters most, where the builder and the parser share a
//! misunderstanding and agree with each other about bytes no real writer emits.
//!
//! Shared by `test_partition_table.zig` and `test_fs_recognise.zig` rather than
//! duplicated into each, because several captures are interesting to both: an
//! MBR is a table to one and a not-a-filesystem to the other.
//!
//! Two of the writers are outside this tree entirely — macOS `newfs_msdos` wrote
//! the FAT volumes and QEMU's vvfat synthesised the ESP disk — so those captures
//! cannot agree with a mistake made here. `mkfs_wfs` and `make_gpt_image.py` are
//! ours, and are the writers whose output this system actually mounts, which is
//! the property worth testing rather than independence.
//!
//! Regenerate with:
//!   qemu-img convert -f vvfat "fat:<esp>" -O raw esp.img    # MBR at 0, FAT at LBA 63
//!   scripts/make_gpt_image.py --output gpt.img --label wasmostest --size-mib 64
//!   scripts/make_gpt_image.py --output gpt_esp.img --label ESP --size-mib 64 --esp
//!   hdiutil attach -imagekey diskimage-class=CRawDiskImage -nomount fat16.img
//!   newfs_msdos -F 16 -v WASMOSFAT16 /dev/diskN     # newfs_msdos needs a device
//!   newfs_msdos -F 32 -v WASMOSFAT32 /dev/diskN
//!   mkfs_wfs --uuid 0123456789ABCDEF0123456789ABCDEF wfs.img 16777216

